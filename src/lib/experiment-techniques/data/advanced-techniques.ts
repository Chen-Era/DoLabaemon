type TechniqueSeed = readonly [
  code: string,
  slug: string,
  nameZh: string,
  nameEn: string,
  aliases: string[],
  subcategoryCode: string,
  preset: TechniqueBlueprint["preset"],
  principleZh: string,
  principleEn: string,
  scopeZh: string,
  scopeEn: string,
  sampleTypes: string[],
  readoutModes: string[],
];

function materializeTechniques(
  categoryCode: TechniqueCategoryCode,
  evidenceSourceIds: string[],
  seeds: TechniqueSeed[],
): TechniqueBlueprint[] {
  return seeds.map(
    ([
      code,
      slug,
      nameZh,
      nameEn,
      aliases,
      subcategoryCode,
      preset,
      principleZh,
      principleEn,
      scopeZh,
      scopeEn,
      sampleTypes,
      readoutModes,
    ]) => ({
      code,
      slug,
      nameZh,
      nameEn,
      aliases,
      categoryCode,
      subcategoryCode,
      preset,
      principleZh,
      principleEn,
      scopeZh,
      scopeEn,
      sampleTypes,
      readoutModes,
      evidenceSourceIds: [...evidenceSourceIds],
    }),
  );
}

