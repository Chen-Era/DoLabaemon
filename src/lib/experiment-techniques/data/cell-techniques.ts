type CategoryLeaf = Omit<
  TechniqueBlueprint,
  "categoryCode" | "evidenceSourceIds" | "reportingStandardIds"
>;

function buildCategory(
  categoryCode: TechniqueCategoryCode,
  evidenceSourceIds: string[],
  reportingStandardIds: string[],
  leaves: CategoryLeaf[],
): TechniqueBlueprint[] {
  return leaves.map((leaf) => ({
    ...leaf,
    categoryCode,
    evidenceSourceIds: [...evidenceSourceIds],
    reportingStandardIds: [...reportingStandardIds],
  }));
}

