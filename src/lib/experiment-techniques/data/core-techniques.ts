type CoreTechniqueInput = Omit<
  TechniqueBlueprint,
  "categoryCode" | "evidenceSourceIds"
> & {
  evidenceSourceIds?: string[];
};

function defineTechnique(
  categoryCode: TechniqueCategoryCode,
  defaultEvidenceSourceIds: string[],
  input: CoreTechniqueInput,
): TechniqueBlueprint {
  return {
    ...input,
    categoryCode,
    evidenceSourceIds:
      input.evidenceSourceIds ?? [...defaultEvidenceSourceIds],
  };
}

